const dicts = { de, ru };

export function translator(lang) {
  const d = dicts[lang] || de;
  const t = (key, vars) => {
    let s = d[key] ?? de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
  t.lang = dicts[lang] ? lang : 'de';
  t.msg = (m) => {
    if (t.lang !== 'ru') return m;
    for (const [re, rep] of ruMessages) if (re.test(m)) return m.replace(re, rep);
    return m;
  };
  return t;
}

export function formatDate(d, lang = 'de', withTime = true) {
  const date = d instanceof Date ? d : new Date(d);
  if (Number.isNaN(date.getTime())) return '';
  const pad = (n) => String(n).padStart(2, '0');
  const ds = `${pad(date.getDate())}.${pad(date.getMonth() + 1)}.${date.getFullYear()}`;
  if (!withTime) return ds;
  return translator(lang)('time.at', { date: ds, time: `${pad(date.getHours())}:${pad(date.getMinutes())}` });
}
